#!/usr/bin/env python3
"""Extract every article in a textbook's docs/ into assets/search-index.js.

Browsers block fetch() of other local files on file://, so the search page reads
this prebuilt JS file instead. Re-run it whenever article text changes:

    python3 build_search_index.py <path-to-docs>
    python3 docs/_tools/build_search_index.py          # copy kept in docs/_tools/

Indexed: the <article class="content"> of docs/index.html, docs/lessons/*.html and
docs/architecture/*.html, split into sections at <h1>/<h2>. search.html is skipped.
"""
from __future__ import annotations

import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

SKIP_PAGES = {"search.html"}
SKIP_TAGS = {"script", "style", "nav", "button", "select"}
BLOCK_TAGS = {
    "p", "li", "td", "th", "tr", "pre", "div", "h1", "h2", "h3", "h4",
    "summary", "details", "blockquote", "br", "ul", "ol", "table",
}
VOID_TAGS = {"br", "img", "hr", "meta", "link", "input", "source", "wbr"}


class ArticleParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.depth = 0          # nesting depth inside <article class="content"> (0 = outside)
        self.skip = 0           # nesting depth inside a skipped tag
        self.title = ""
        self.sections: list[dict] = []
        self._buf: list[str] = []
        self._heading: str | None = None   # text of the h1/h2 being read
        self._heading_tag = ""

    def _flush(self, new_heading: str | None) -> None:
        text = re.sub(r"\s+", " ", "".join(self._buf)).strip()
        if text and self.sections:
            self.sections[-1]["t"] = (self.sections[-1]["t"] + " " + text).strip()
        self._buf = []
        if new_heading is not None:
            self.sections.append({"h": new_heading, "t": ""})

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if self.depth == 0:
            if tag == "article" and "content" in (a.get("class") or "").split():
                self.depth = 1
            return
        if tag not in VOID_TAGS:
            self.depth += 1
        if self.skip:
            if tag not in VOID_TAGS:
                self.skip += 1
            return
        if tag in SKIP_TAGS:
            self.skip = 1
            return
        if tag in ("h1", "h2"):
            self._heading, self._heading_tag = "", tag
            return
        if tag in BLOCK_TAGS:
            self._buf.append(" ")

    def handle_endtag(self, tag):
        if self.depth == 0:
            return
        if tag not in VOID_TAGS:
            self.depth -= 1
        if self.skip:
            self.skip -= 1
            return
        if self._heading is not None and tag == self._heading_tag:
            heading = re.sub(r"\s+", " ", self._heading).strip()
            if tag == "h1":
                self.title = heading
            self._flush(heading)
            self._heading = None
            return
        if tag in BLOCK_TAGS:
            self._buf.append(" ")

    def handle_data(self, data):
        if self.depth == 0 or self.skip:
            return
        if self._heading is not None:
            self._heading += data
        else:
            self._buf.append(data)

    def close(self):
        super().close()
        self._flush(None)


def chapter_key(p: Path) -> list[int]:
    return [int(n) for n in re.findall(r"\d+", p.name)] or [0]


def main() -> None:
    # Without an argument, assume this file lives in docs/_tools/
    docs = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    if not (docs / "assets").is_dir():
        sys.exit(f"not a docs folder (no assets/): {docs}")
    out = docs / "assets" / "search-index.js"
    pages = sorted(docs.glob("index.html"))
    for sub in ("lessons", "architecture"):
        pages += sorted((docs / sub).glob("*.html"), key=chapter_key)
    index = []
    for path in pages:
        if path.name in SKIP_PAGES:
            continue
        parser = ArticleParser()
        parser.feed(path.read_text(encoding="utf-8"))
        parser.close()
        sections = [s for s in parser.sections if s["t"] or s["h"]]
        if not sections:
            continue
        index.append({
            "url": path.relative_to(docs).as_posix(),
            "title": parser.title or path.stem,
            "sections": sections,
        })
    payload = json.dumps(index, ensure_ascii=False, separators=(",", ":"))
    out.write_text(
        "// Generated by build_search_index.py. Do not edit.\n"
        f"window.SEARCH_INDEX = {payload};\n",
        encoding="utf-8",
    )
    total = sum(len(p["sections"]) for p in index)
    print(f"{out}: {len(index)} pages, {total} sections, {out.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
